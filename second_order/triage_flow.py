def simulate(request: httpx.Request) -> httpx.Response:
    """The server's local simulation: a Messages-API-shaped placeholder built from the request alone. No model reads
    the entries, so every result says only that; nothing leaves this process."""
    try:
        body = json.loads(request.content)
        ids = body["output_config"]["format"]["schema"]["properties"]["results"]["items"]["properties"]["id"].get(
            "enum", [])
    except (ValueError, KeyError, TypeError, AttributeError):
        return httpx.Response(400, json={"type": "error", "error": {"type": "invalid_request_error",
                                                                     "message": "Not a triage request"}})
    reply = {"results": [{"id": item_id, "category": "Insufficient information", "event_type": None,
                          "summary": "Simulated placeholder: no model read this entry."} for item_id in ids],
             "relations": []}
    message = {"id": f"msg_simulated_{sha256(request.content)[:20]}", "type": "message", "role": "assistant",
               "model": body.get("model"), "content": [{"type": "thinking", "thinking": "", "signature": "sig-simulated"},
                                                       {"type": "text", "text": canonical(reply)}],
               "stop_reason": "end_turn", "stop_sequence": None, "usage": {"input_tokens": 0, "output_tokens": 0}}
    return httpx.Response(200, content=canonical(message).encode("utf-8"), headers={"content-type": "application/json"})


def simulated_client(handler: Callable[[httpx.Request], httpx.Response] = simulate):
    """A client factory whose transport is an in-process simulation: it has no network at all."""
    def factory(observe: Callable[[httpx.Response], None]) -> httpx.Client:
        return httpx.Client(transport=httpx.MockTransport(handler), trust_env=False, follow_redirects=False,
                            event_hooks={"response": [observe]})
    return factory


@dataclass(frozen=True)
class TriageSenders:
    """How this server answers an approved triage, chosen at startup only; no API route creates or changes it. The
    simulation is always local. ``paid`` exists only on a server started with --enable-paid-triage (or in tests)."""
    simulated: Callable[[Callable[[httpx.Response], None]], httpx.Client] = simulated_client()
    paid: PaidSender | None = None


def paid_status(sender: PaidSender | None) -> dict:
    if sender is None:
        return {"enabled": False, "detail": NOT_ENABLED}
    problem = key_problem(sender.api_key())
    return {"enabled": problem is None, "detail": f"{problem}; paid triage is unavailable" if problem else
            f"Paid triage is enabled: each request is sent once, to {MODEL}, only after its own explicit approval."}


class _NoReply(Exception):
    pass


class _CredentialEcho(Exception):
    pass


class _ProviderError(Exception):
    pass


def _post(client: httpx.Client, body: bytes, api_key: str | None) -> bytes:
    """POST exactly these bytes once. Every reply is checked for the credential before any of it is read."""
    headers = {"anthropic-version": API_VERSION, "content-type": "application/json"}
    if api_key:
        headers["x-api-key"] = api_key
    try:
        response = client.post(MESSAGES_URL, content=body, headers=headers)
    except httpx.HTTPError as exc:
        raise _NoReply(type(exc).__name__) from None
    if api_key and exposes(response.content, api_key):
        raise _CredentialEcho()
    if response.status_code != 200:
        try:
            kind = response.json()["error"]["type"]
        except (ValueError, KeyError, TypeError):
            kind = None
        raise _ProviderError(f"HTTP {response.status_code}" + (f" ({kind})" if isinstance(kind, str) and
                                                               SAFE_WORD.fullmatch(kind) else ""))
    return response.content


OUTCOME_NOTES = {
    "triaged": "The response passed strict validation: one result per entry, categories from the taxonomy, summaries "
               "within the validation policy's technical limit and relations only within the request's saved "
               "comparison pairs. It is a suggestion to check, not a finding.",
    "not_accepted": "The response did not pass strict validation, so nothing from it is shown as triage. Its bytes are "
                    "kept in response.json.",
    "provider_error": "The provider returned an error status. Its body is not kept; the request ID links the call to "
                      "the Console.",
    "no_reply": "No complete response arrived, and nothing is sent again.",
    "credential_echo": "The response contained the credential, so nothing from it was kept.",
}


def dispatch(triage_id: str, mode: str, body: bytes, senders: TriageSenders, triage_dir: Path = TRIAGE_DIR,
             clock: Callable[[], datetime] = now, policy: str | None = None) -> dict:
    """Validate an approval, claim the request's entries, reserve this mode's single attempt, post the saved request
    bytes once and record the exchange. Simulated: the local transport, $0. Paid: only when enabled, after the
    estimate and key checks. The reply is checked under ``policy`` (by default the current one, read now), which the
    manifest names; the API never chooses it."""
    policy = policy or headline_triage.VALIDATION_POLICY
    if mode not in MODES:
        raise TriageRefused(404, "Unknown triage mode")
    if mode == "paid" and senders.paid is None:
        raise TriageRefused(409, NOT_ENABLED)
    fields = ("request_sha256", "approve_simulated_response", "reprocess_ids", "comparison_pairs") \
        if mode == "simulated" else \
        ("request_sha256", "approve_paid_request", "estimated_max_usd", "reprocess_ids", "comparison_pairs")
    try:
        approval = strict_object(body, fields, f"{mode} approval")
    except FlowRefused as exc:
        raise TriageRefused(exc.status, str(exc)) from None
    if not isinstance(approval["request_sha256"], str):
        raise TriageRefused(422, "request_sha256 must be text")
    if approval[fields[1]] is not True:
        raise TriageRefused(422, f"{fields[1]} must be true: a response is requested only after explicit approval")
    reprocess = approval["reprocess_ids"]
    if not isinstance(reprocess, list) or not all(isinstance(item_id, str) for item_id in reprocess):
        raise TriageRefused(422, "reprocess_ids must list the entry IDs the approval explicitly re-requests")
    approved_pairs = approval["comparison_pairs"]
    try:
        if not isinstance(approved_pairs, list) or not all(isinstance(pair, list) for pair in approved_pairs):
            raise ValueError
        approved_pairs = canonical_pairs(approved_pairs)
    except ValueError:
        raise TriageRefused(422, "comparison_pairs must repeat the pairs the preview planned to compare, each once") \
            from None
    record = load_record(triage_dir, triage_id)
    if approval["request_sha256"] != record["request_sha256"]:
        raise TriageRefused(409, "The approved request SHA-256 does not match the saved request; nothing was reserved "
                                 "or sent")
    if record["pairs"] is None:
        raise TriageRefused(409, f"{LEGACY}. Preview the selection again to prepare a request with an explicit "
                                 "comparison scope; nothing was reserved or sent")
    if approved_pairs != record["pairs"]:
        raise TriageRefused(409, "The approved comparison pairs are not this request's saved comparison scope; nothing "
                                 "was reserved or sent. Approve exactly the pairs its preview showed, or preview again")
    request_bytes, api_key, estimate = record["request_bytes"], None, None
    if mode == "paid":
        submitted = approval["estimated_max_usd"]
        if isinstance(submitted, bool) or not isinstance(submitted, (int, float)):
            raise TriageRefused(422, "estimated_max_usd must repeat the estimate the preview showed")
        api_key = senders.paid.api_key()
        problem = key_problem(api_key)
        if problem:
            raise TriageRefused(409, f"{problem}; nothing was reserved or sent")
        estimate = cost_estimate(request_bytes, record["request"]["max_tokens"],
                                 record["context"])["estimated_paid_if_output_reaches_max_usd"]
        if round(float(submitted), 4) != estimate:
            raise TriageRefused(409, f"The approved estimate does not match this request's planning estimate "
                                     f"(${estimate}); nothing was reserved or sent")
        if exposes(request_bytes, api_key):
            raise TriageRefused(409, "The saved request would carry the credential; nothing was reserved or sent")
    factory = senders.simulated if mode == "simulated" else senders.paid.client_factory
    earlier = read_attempts(record, mode)
    if any(usable(attempt) for attempt in earlier):
        raise TriageRefused(409, f"This request already has an accepted {mode} result (on receipt or on a local "
                                 "re-check); it is never requested again. Its saved result is shown instead")
    entry_ids = {entry["id"] for entry in record["entries"]}
    supplied = entry_ids | {entry["id"] for entry in record["context"]}
    if earlier and (not entry_ids <= set(reprocess) or not supplied & set(reprocess)):
        raise TriageRefused(409, f"This request was already attempted in this mode ({earlier[-1]['state']}"
                                 f"{', ' + earlier[-1]['outcome'] if earlier[-1].get('outcome') else ''}). Requesting "
                                 "it again needs an explicit decision for each of its entries; nothing was reserved or "
                                 "sent")
    # The comparison work as it stands now must be exactly the saved scope: work done, reserved or left unresolved
    # elsewhere since then makes this approval stale. A fresh preview prepares a new request; these bytes are never
    # rewritten and the scope never changes to fit.
    from . import triage_plan  # Here, not at the top: triage_plan builds on this module.
    settings_key = config_key(record["config"])
    rows = [{"input": entry, "fingerprint": fingerprint(entry), "reprocess": entry["id"] in set(reprocess)}
            for entry in record["entries"] + record["context"]]
    needed = triage_plan.comparison_work(rows, mode, settings_key, triage_plan.build_index(triage_dir),
                                         triage_dir)["needed"]
    planned = {frozenset(pair) for pair in record["pairs"]}
    current = {frozenset((a["input"]["id"], b["input"]["id"])) for a, b in needed}
    if planned != current:
        gone, new = len(planned - current), len(current - planned)
        extra = f", and {new} more {'is' if new == 1 else 'are'} now needed" if new else ""
        raise TriageRefused(409, f"This request's comparison work changed since its preview: {gone} of its planned "
                                 f"comparisons {'was' if gone == 1 else 'were'} done, reserved or left unresolved by "
                                 f"another request{extra}. Nothing was reserved or sent; preview again")
    if not record["entries"] and not record["pairs"]:
        raise TriageRefused(409, "Everything this request would ask for is already done or reserved, so it is not "
                                 "sent. Nothing was reserved or sent; preview again")
    name = mode if not earlier else f"{mode}-{len(earlier) + 1}"
    by_id = {row["input"]["id"]: row for row in rows}
    work = [(result_key(entry, record["config"]), f"“{entry['title'][:80]}”", {entry["id"]})
            for entry in record["entries"]]
    work += [(pair_key(by_id[a]["fingerprint"], by_id[b]["fingerprint"], settings_key),
              f"the comparison of “{by_id[a]['input']['title'][:60]}” and “{by_id[b]['input']['title'][:60]}”",
              {a, b}) for a, b in record["pairs"]]
    claims = _claim_work(record, mode, name, work, set(reprocess), triage_dir, clock)
    attempt = record["folder"] / name
    try:
        attempt.mkdir()  # The reservation: created exclusively, never released by code.
    except FileExistsError:
        for path in claims:
            path.unlink(missing_ok=True)
        raise TriageRefused(409, f"This request is already being attempted in this mode; it is never sent twice "
                                 "without an explicit decision. Read it again to see what was recorded") from None
    except OSError:
        for path in claims:
            path.unlink(missing_ok=True)
        raise

    sent_at = None
    try:
        names = {"triage_id": triage_id, "mode": mode, "attempt": name, "model": record["config"]["model"],
                 "request_sha256": record["request_sha256"]}
        reserved_at = utc(clock()).isoformat()
        keep_record(attempt / "reservation.json", _json_bytes({**names, "reserved_at": reserved_at,
                                                               "pid": os.getpid()}), api_key)
        seen: dict = {}

        def observe(response: httpx.Response) -> None:  # Status and request ID only; _post checks the body.
            seen["http_status"] = response.status_code
            request_id = response.headers.get("request-id", "")
            if REQUEST_ID.fullmatch(request_id) and not (api_key and api_key in request_id):
                seen["request_id"] = request_id

        sent_at = utc(clock())
        keep_record(attempt / "attempt.json", _json_bytes({"state": "sending", "mode": mode,
                                                          "sent_at": sent_at.isoformat(), "attempts": 1,
                                                          "retries": 0}), api_key)
        received, message = None, None
        try:
            with factory(observe) as client:
                received = _post(client, request_bytes, api_key)  # The one transport call.
        except _NoReply as exc:
            outcome = "no_reply"
            message = (f"No reply arrived ({exc}). {UNKNOWN}" if mode == "paid" else
                       f"No reply arrived from the local simulation ({exc}). Nothing was billed or sent anywhere.")
        except _CredentialEcho:
            outcome, message = "credential_echo", None
        except _ProviderError as exc:
            outcome, message = "provider_error", f"The provider answered {exc}"
        received_at = utc(clock())
        summary = {}
        if received is not None:
            keep_record(attempt / "response.json", received, api_key)
            summary = response_summary(received)
            try:
                parse_response(received, record["entries"], record["context"], record["config"]["model"],
                               scope=record["pairs"], policy=policy)
                outcome, message = "triaged", None
            except ResponseRejected as exc:
                outcome, message = "not_accepted", str(exc)
        manifest = {
            **names, "triage_version": TRIAGE_VERSION, "config": record["config"],
            "max_tokens": record["request"]["max_tokens"], "request_bytes": len(request_bytes),
            "entry_ids": [entry["id"] for entry in record["entries"]],
            "context_ids": [entry["id"] for entry in record["context"]], "reprocess_ids": sorted(reprocess),
            "comparison_pairs": record["pairs"], "validation_policy": policy,
            "validation_statement": VALIDATION_POLICIES[policy]["statement"],
            "endpoint": MESSAGES_URL if mode == "paid" else "local simulation in this server; no endpoint contacted",
            "anthropic_version": API_VERSION if mode == "paid" else None, "reserved_at": reserved_at,
            "sent_at": sent_at.isoformat(), "received_at": received_at.isoformat(),
            "elapsed_seconds": (received_at - sent_at).total_seconds(), "http_status": seen.get("http_status"),
            "request_id": seen.get("request_id"),
            "response": None if received is None else {"sha256": sha256(received), "bytes": len(received), **summary},
            "outcome": outcome, "outcome_note": OUTCOME_NOTES[outcome], "adapter_message": message,
            "cost": usage_cost(summary.get("usage")) if mode == "paid" else {"usd": 0, "basis": "local simulation"},
            "planning_estimate_usd": estimate, "attempts": 1, "retries": 0, "fallbacks": None,
            "provenance": ("Requested once by this server after an explicit approval in the Event Inbox. The request "
                           "was exactly the saved request.json, never rebuilt. response.json, when present, holds the "
                           "exact bytes received" + (" after the credential check." if mode == "paid" else
                                                     " from the local simulation; no provider was contacted.")),
        }
        keep_record(attempt / "manifest.json", _json_bytes(manifest), api_key)  # Written last: it marks completion.
    except TriageRefused:
        raise
    except Exception as exc:
        sent = f" after it was sent. {UNKNOWN}" if sent_at is not None and mode == "paid" else "."
        raise TriageRefused(500, f"The {mode} attempt was interrupted ({type(exc).__name__}){sent} What was written is "
                                 "kept, and it is never requested again in this mode.") from None
    return {**request_view(triage_id, triage_dir), "provider_called": mode == "paid" and sent_at is not None}
