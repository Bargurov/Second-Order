"""Headline triage, saved requests: the exact request for one planned batch, one approval per mode, and the record of
what was sent and received.

What to request is decided in triage_plan, from saved results; this module saves and sends exactly that. A request
lives in `requests/<triage-id>/` under the triage folder (data/headline-triage/, ignored by git): selection.json (the
entries to triage, the comparison context, as snapshots, and the comparison scope) and request.json (the exact bytes,
which carry the same scope), then prepared.json last (configuration, scope, hashes, the estimate). The ID comes from the
request's SHA-256, so saving the same plan again writes nothing, and a different scope is a different request.

Approval follows the Tracker's pattern: the request's SHA-256, an explicit true, and for a paid request the planning
estimate repeated and checked. It also repeats the request's saved comparison scope (comparison_pairs); an approval
naming any other pairs is refused. Dispatch then recomputes the request's comparison work as it stands and refuses when
it is no longer exactly the saved scope (work done, reserved or left unresolved elsewhere since), before anything is
reserved: a fresh preview is needed, which prepares a new request, and saved bytes are never rewritten. Then every piece
of work is claimed in that mode, each claim created exclusively: every entry to triage
(`claims/<mode>/<fingerprint>-<config>/`) and every comparison in the saved scope
(`claims/<mode>/pairs/<both fingerprints in canonical order>-<config>/`). A reply is accepted only if every relation it
suggests stays within that scope (headline_triage.parse_response).

A request saved under headline-triage-0.2 has no comparison scope: its reply's relations were never limited to planned
comparisons. It stays readable, with its provenance and anything it recorded, and is never sent again in either mode.

Each attempt's manifest names the validation policy its response was checked under (headline_triage.VALIDATION_POLICIES).
A response that was not accepted can be re-checked locally, by explicit action, under the current policy
(triage_recheck.revalidate):
its saved bytes are parsed again, nothing is sent, regenerated or repaired, and the outcome is written apart, to
`<attempt>/revalidations/<policy>.json`, created once. The attempt's own files never change, so its original outcome
stays beside the re-check. A response accepted on such a re-check is a usable result, labelled as such; it was still
generated by the original request, under that request's prompt and schema. Work with a saved result
is never requested again; work an earlier request claimed (in flight, failed or uncertain) is refused unless the
approval re-requests one of its entries by ID. Repeated clicks, other tabs and other server processes therefore cannot
send one entry or one comparison twice without that explicit decision. A request is attempted once per mode (folder
`simulated` or `paid`, created exclusively); a further attempt (`paid-2`, ...) exists only when no attempt was
accepted and the approval re-requests every one of its entries. The saved bytes are posted once per attempt, never
rebuilt, with no retry (the client has none), repair, re-send or fallback. A lost paid reply is recorded as an unknown
outcome. Claims and attempts are never released once a request may have been sent, so failed or uncertain work stays
visible and never returns to the queue on its own.

Simulated responses come from an in-process transport with no network; paid ones only from a server started with
--enable-paid-triage. Triage records never touch captures, analysis attempts, drafts or reviews. Reads never call a
model or write anything; a record that does not verify is reported, never repaired.
"""
