def load_record(triage_dir: Path, triage_id: str) -> dict:
    """A saved, verified request: the request's hash names it, and its selection is the one the request carries.
    Read only; a record that does not verify is reported, never repaired."""
    if not TRIAGE_ID.fullmatch(triage_id or ""):
        raise TriageRefused(404, "Unknown triage ID")
    folder = requests_dir(triage_dir) / triage_id
    if not folder.is_dir():
        raise TriageRefused(404, "Unknown triage ID")
    try:
        request_bytes = (folder / "request.json").read_bytes()
        selection_bytes = (folder / "selection.json").read_bytes()
        prepared = json.loads((folder / "prepared.json").read_text(encoding="utf-8"))
    except FileNotFoundError:
        raise TriageRefused(409, "This request's preparation did not finish. Previewing the same entries again "
                                 "completes it; nothing is sent by previewing") from None
    except (OSError, ValueError):
        raise TriageRefused(409, "This request's saved files cannot be read; they are left as they are") from None
    request_hash = sha256(request_bytes)
    pairs, problem = None, None
    try:
        selection = json.loads(selection_bytes.decode("utf-8"))
        request = strict_json(request_bytes)
        version = selection["triage_version"]
        entries, context = selection["entries"], selection["context"]
        entry_ids = [entry["id"] for entry in entries]
        supplied = entry_ids + [entry["id"] for entry in context]
        schema = request["output_config"]["format"]["schema"]["properties"]
        if version == TRIAGE_VERSION:  # The comparison scope: canonical, of supplied IDs, the same in every file.
            pairs = selection["comparison_pairs"]
        elif version != LEGACY_TRIAGE_VERSION:  # 0.2 records carry no scope and are read as they were saved.
            raise ValueError(f"unknown triage version {version}")
        if pairs is not None and (pairs != canonical_pairs(pairs) or prepared["comparison_pairs"] != pairs or
                                  any(item not in supplied for pair in pairs for item in pair)):
            problem = "its comparison scope is not canonical pairs of its own entries"
        elif f"triage-{request_hash[:24]}" != triage_id or prepared["request_sha256"] != request_hash:
            problem = "its request.json is not the request this triage ID names"
        elif prepared["selection_sha256"] != sha256(selection_bytes) or selection["triage_id"] != triage_id or \
                prepared["triage_version"] != version:
            problem = "its selection.json does not match its preparation record"
        elif request["model"] != prepared["config"]["model"] or \
                not request["messages"][0]["content"].endswith(f"\n\n{payload_json(entries, context, pairs)}") or \
                schema["results"]["items"]["properties"]["id"].get("enum", []) != entry_ids or \
                schema["relations"]["items"]["properties"]["item_ids"]["items"]["enum"] != relation_ids(supplied, pairs):
            problem = "its request does not carry exactly its saved selection and comparison scope"
    except (DraftRefused, KeyError, TypeError, IndexError, ValueError, AttributeError):
        problem = "its files are malformed"
    if problem:
        raise TriageRefused(409, f"This saved request does not verify: {problem}. It is left as it is")
    return {"folder": folder, "triage_id": triage_id, "request": request, "request_bytes": request_bytes,
            "request_sha256": request_hash, "entries": entries, "context": context, "prepared": prepared,
            "config": prepared["config"], "triage_version": version, "pairs": pairs}


def _write_once(path: Path, data: bytes) -> bool:
    """Write a file that must hold exactly these bytes. False if it already did; TriageRefused if it holds others."""
    try:
        keep_record(path, data)
        return True
    except FileExistsError:
        if path.read_bytes() != data:
            raise TriageRefused(409, "A different saved request uses this ID; nothing was changed") from None
        return False


def save_request(entries: list[dict], context: list[dict], pairs: list[list[str]], triage_dir: Path,
                 clock: Callable[[], datetime] = now) -> tuple[str, bool]:
    """Save one planned request: its snapshots, its comparison scope (the missing comparison work it was planned for,
    canonical) and its exact bytes, before any approval. Returns its ID and whether anything was written; an identical
    saved request is reused as it is."""
    request = build_request(entries, context, pairs)
    request_bytes = canonical(request).encode("utf-8")
    request_hash = sha256(request_bytes)
    triage_id = f"triage-{request_hash[:24]}"
    selection_bytes = _json_bytes({"triage_version": TRIAGE_VERSION, "triage_id": triage_id, "entries": entries,
                                   "context": context, "comparison_pairs": pairs})
    folder = requests_dir(triage_dir) / triage_id
    folder.mkdir(parents=True, exist_ok=True)
    wrote = _write_once(folder / "selection.json", selection_bytes)
    wrote = _write_once(folder / "request.json", request_bytes) or wrote
    try:  # Written last: it marks the preparation complete. An existing one, even from a concurrent run, is kept.
        keep_record(folder / "prepared.json", _json_bytes({
            "triage_version": TRIAGE_VERSION, "triage_id": triage_id,
            "prepared_at": utc(clock()).isoformat(timespec="seconds"), "config": config(),
            "max_tokens": request["max_tokens"], "request_sha256": request_hash, "request_bytes": len(request_bytes),
            "selection_sha256": sha256(selection_bytes), "entry_ids": [entry["id"] for entry in entries],
            "context_ids": [entry["id"] for entry in context], "comparison_pairs": pairs,
            "cost_estimate": cost_estimate(request_bytes, request["max_tokens"], context),
            "provenance": ("Prepared from the local Event Inbox and saved triage results only: no feed or linked "
                           "article was requested and no model was called. request.json holds the exact bytes any "
                           "approved response is requested with; selection.json holds the entries it carries and "
                           "the comparison pairs, the only ones a reply may relate.")}))
        wrote = True
    except FileExistsError:
        pass
    return triage_id, wrote


def attempt_names(record: dict, mode: str) -> list[str]:
    """This mode's attempt folders in order: the first is named after the mode; later ones, each made only by an
    explicit re-request after an attempt that produced no accepted result, are mode-2, mode-3 and so on."""
    found = []
    for path in record["folder"].iterdir():
        match = re.fullmatch(rf"{mode}(?:-([1-9][0-9]*))?", path.name)
        if path.is_dir() and match and (match.group(1) is None or int(match.group(1)) >= 2):
            found.append((int(match.group(1) or 1), path.name))
    return [name for _, name in sorted(found)]


def read_attempt(record: dict, mode: str, name: str | None = None) -> dict:
    """What one attempt (by default this mode's latest) recorded. Read only: nothing is written, repaired, sent or
    generated."""
    name = name or (attempt_names(record, mode) or [mode])[-1]
    attempt = record["folder"] / name
    if not attempt.is_dir():
        return {"mode": mode, "attempt": name, "state": "none"}
    names = sorted(path.name for path in attempt.iterdir() if not path.name.startswith(".tmp-"))
    if "manifest.json" not in names:
        sent = "attempt.json" in names
        detail = ("A paid request was sent and no response is recorded. It may still be in flight, or the server stopped "
                  "before recording it; the provider may have received and billed it. It is never sent again on its "
                  "own. Check the Console's usage for that time." if mode == "paid" and sent else
                  "A response was reserved but not recorded. The reservation is kept; this request is attempted again "
                  "in this mode only by an explicit re-request.")
        return {"mode": mode, "attempt": name, "state": "incomplete", "sent": sent, "files": names, "detail": detail}
    try:
        manifest = json.loads((attempt / "manifest.json").read_text(encoding="utf-8"))
        result = None
        if manifest["request_sha256"] != record["request_sha256"] or manifest["attempt"] != name:
            raise ValueError("the attempt names another request")
        policy = manifest.get("validation_policy", FIRST_POLICY)
        if policy not in VALIDATION_POLICIES:
            raise ValueError("the attempt names an unknown validation policy")
        if manifest["outcome"] == "triaged":  # Re-verified on every read, under the policy it was accepted with.
            received = (attempt / "response.json").read_bytes()
            if sha256(received) != manifest["response"]["sha256"]:
                raise ValueError("response.json is not the recorded response")
            result = parse_response(received, record["entries"], record["context"], record["config"]["model"],
                                    scope=record["pairs"], policy=policy)
        checks = _revalidations(record, attempt, name, manifest) if manifest["outcome"] == "not_accepted" else []
    except (OSError, ValueError, KeyError, TypeError, ResponseRejected) as exc:
        return {"mode": mode, "attempt": name, "state": "invalid", "files": names,
                "detail": f"The recorded attempt does not verify ({type(exc).__name__}); it is left as it is."}
    return {"mode": mode, "attempt": name, "state": "complete", "outcome": manifest["outcome"],
            "outcome_note": manifest["outcome_note"],
            "message": manifest["adapter_message"], "sent_at": manifest["sent_at"],
            "received_at": manifest["received_at"], "http_status": manifest["http_status"],
            "request_id": manifest["request_id"], "usage": (manifest["response"] or {}).get("usage"),
            "cost": manifest["cost"], "comparison_pairs": manifest.get("comparison_pairs"), "validation_policy": policy,
            "response_sha256": (manifest["response"] or {}).get("sha256"),
            "revalidations": [{key: value for key, value in check.items() if key != "parsed"} for check in checks],
            "revalidation": next((check for check in checks if check["current_policy"]), None), "parsed": result}


def _revalidations(record: dict, attempt: Path, name: str, manifest: dict) -> list[dict]:
    """The local re-checks of one not-accepted response, each verified against the saved response; an accepted one is
    parsed again now, under the policy it names. Reads only; one that does not verify is reported, never repaired."""
    folder = attempt / "revalidations"
    found = []
    for path in sorted(folder.glob("*.json")) if folder.is_dir() else []:
        try:
            check = json.loads(path.read_text(encoding="utf-8"))
            received = (attempt / "response.json").read_bytes()
            if (check["revalidation_version"], check["triage_id"], check["attempt"], check["validation_policy"]) != \
                    (REVALIDATION_VERSION, record["triage_id"], name, path.stem) or \
                    not check["response_sha256"] == sha256(received) == manifest["response"]["sha256"] or \
                    check["outcome"] not in ("accepted", "not_accepted") or path.stem not in VALIDATION_POLICIES:
                raise ValueError("the re-check names another response or policy")
            parsed = parse_response(received, record["entries"], record["context"], record["config"]["model"],
                                    scope=record["pairs"], policy=path.stem) if check["outcome"] == "accepted" else None
            found.append({"state": "complete", "validation_policy": path.stem, "current_policy": path.stem ==
                          headline_triage.VALIDATION_POLICY, "revalidated_at": check["revalidated_at"],
                          "outcome": check["outcome"],
                          "message": check["message"], "parsed": parsed})
        except (OSError, ValueError, KeyError, TypeError, ResponseRejected) as exc:
            found.append({"state": "invalid", "validation_policy": path.stem, "current_policy": path.stem ==
                          headline_triage.VALIDATION_POLICY, "outcome": None, "parsed": None,
                          "detail": f"This local re-check does not verify ({type(exc).__name__}); it is left as it is."})
    return found


def read_attempts(record: dict, mode: str) -> list[dict]:
    return [read_attempt(record, mode, name) for name in attempt_names(record, mode)]


def accepted(attempt: dict) -> bool:
    """Accepted when it was received, under the policy it was checked with then."""
    return attempt["state"] == "complete" and attempt["outcome"] == "triaged"


def revalidated(attempt: dict) -> bool:
    """Not accepted when received, but accepted on an explicit local re-check under the current policy."""
    check = attempt.get("revalidation") if attempt["state"] == "complete" else None
    return bool(check) and check["state"] == "complete" and check["outcome"] == "accepted"


def usable(attempt: dict) -> bool:
    return accepted(attempt) or revalidated(attempt)


def parsed_result(attempt: dict) -> dict:
    """The parsed response of a usable attempt: as accepted on receipt, or as accepted on its local re-check."""
    return attempt["parsed"] if accepted(attempt) else attempt["revalidation"]["parsed"]


def revalidation_view(attempt: dict) -> dict | None:
    check = attempt.get("revalidation")
    return None if check is None else {key: value for key, value in check.items() if key != "parsed"}


def revalidatable(record: dict, attempt: dict) -> bool:
    """Whether an explicit local re-check under the current policy is possible and not yet made."""
    return record["pairs"] is not None and attempt["state"] == "complete" and attempt["outcome"] == "not_accepted" \
        and bool(attempt.get("response_sha256")) and attempt.get("revalidation") is None


def batch_result(parsed: dict, record: dict) -> dict:
    """An accepted response laid out over the request's own entries and comparison context."""
    by_id = {entry["id"]: entry for entry in record["entries"] + record["context"]}
    return {"entries": [{"id": entry["id"], **entry_result(parsed["results"][entry["id"]], entry)}
                        for entry in record["entries"]],
            "relations": [{**relation, "label": RELATIONS[relation["relation"]],
                           "feed_dates": feed_dates([by_id[member] for member in relation["item_ids"]])}
                          for relation in parsed["relations"]],
            "response_id": parsed["response_id"], "thinking_blocks": parsed["thinking_blocks"]}


def public_attempt(attempt: dict, record: dict) -> dict:
    """An attempt as the page sees it: the parsed response replaced by its layout over the request."""
    shown = {key: value for key, value in attempt.items() if key not in ("parsed", "revalidation")}
    if attempt["state"] == "complete":
        shown["revalidation"] = revalidation_view(attempt)
        shown["result"] = batch_result(parsed_result(attempt), record) if usable(attempt) else None
        shown["result_basis"] = ("accepted_on_receipt" if accepted(attempt) else "accepted_on_local_recheck"
                                 if revalidated(attempt) else None)
        shown["revalidatable"] = revalidatable(record, attempt)
    return shown


def request_view(triage_id: str, triage_dir: Path = TRIAGE_DIR) -> dict:
    """A saved request: its exact entries, comparison context and bytes, its configuration and estimate, and what each
    mode recorded. Reads only."""
    record = load_record(triage_dir, triage_id)
    prepared = record["prepared"]
    scoped = record["pairs"] is not None
    rebuilt = canonical(build_request(record["entries"], record["context"], record["pairs"])).encode("utf-8") \
        if scoped else None
    return {
        "view_version": VIEW_VERSION, "triage_version": TRIAGE_VERSION, "triage_id": triage_id,
        "record_version": record["triage_version"], "comparison_pairs": record["pairs"], "sendable": scoped,
        "contract": f"{SCOPED}." if scoped else f"{LEGACY}.",
        "prepared_at": prepared["prepared_at"], "provider_called": False, "config": record["config"],
        "current_config": config_key(record["config"]) == config_key(config()),
        "max_tokens": record["request"]["max_tokens"], "request_sha256": record["request_sha256"],
        "request_bytes": len(record["request_bytes"]), "request": record["request"], "entries": record["entries"],
        "context": record["context"],
        "current_builder": ("matches: this code builds the same bytes for these entries and pairs" if rebuilt ==
                            record["request_bytes"] else "differs: this request was prepared by another version"),
        "cost_estimate": cost_estimate(record["request_bytes"], record["request"]["max_tokens"], record["context"]),
        "taxonomy": CATEGORIES, "relation_labels": RELATIONS,
        "attempts": {mode: public_attempt(read_attempt(record, mode), record) for mode in MODES},
        "attempt_history": {mode: [{key: attempt.get(key) for key in ("attempt", "state", "outcome", "sent_at")}
                                   for attempt in read_attempts(record, mode)] for mode in MODES},
    }


def records(triage_dir: Path) -> tuple[list[dict], list[dict]]:
    """Every saved request that verifies, and every one that does not (with the reason). Reads only."""
    good, bad = [], []
    folder = requests_dir(triage_dir)
    for path in sorted(folder.iterdir()) if folder.is_dir() else []:
        if not path.is_dir() or not TRIAGE_ID.fullmatch(path.name):
            continue
        try:
            good.append(load_record(triage_dir, path.name))
        except TriageRefused as exc:
            bad.append({"triage_id": path.name, "detail": str(exc)})
    return good, bad


def listing(triage_dir: Path = TRIAGE_DIR) -> dict:
    """Every saved request, newest first, with what each mode recorded; an unreadable one is listed, never hidden. A
    failed or uncertain attempt stays listed here. Reads only."""
    good, bad = records(triage_dir)
    rows = [{"triage_id": row["triage_id"], "state": "unreadable", "detail": row["detail"], "prepared_at": None}
            for row in bad]
    for record in good:
        attempts = {mode: read_attempt(record, mode) for mode in MODES}
        rows.append({"triage_id": record["triage_id"], "state": "ready", "prepared_at": record["prepared"]["prepared_at"],
                     "entry_count": len(record["entries"]), "context_count": len(record["context"]),
                     "titles": [entry["title"] for entry in (record["entries"] + record["context"])[:3]],
                     "item_ids": [entry["id"] for entry in record["entries"] + record["context"]],
                     "current_config": config_key(record["config"]) == config_key(config()),
                     "comparison_pairs": record["pairs"], "sendable": record["pairs"] is not None,
                     "attempts": {mode: {"state": value["state"], "outcome": value.get("outcome"),
                                         "attempts": len(attempt_names(record, mode)),
                                         "detail": value.get("message") or value.get("detail"),
                                         "attempt": value["attempt"], "validation_policy": value.get("validation_policy"),
                                         "response_sha256": value.get("response_sha256"),
                                         "revalidation": revalidation_view(value) if value["state"] == "complete" else None,
                                         "revalidatable": revalidatable(record, value)}
                                  for mode, value in attempts.items()}})
    rows.sort(key=lambda row: row["prepared_at"] or "", reverse=True)
    return {"view_version": VIEW_VERSION, "triage_version": TRIAGE_VERSION, "requests": rows}


