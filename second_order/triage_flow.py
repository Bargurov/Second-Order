def _claims(triage_dir: Path, mode: str, key: str) -> list[int]:
    folder = triage_dir / "claims" / mode / key
    return sorted(int(path.stem) for path in folder.glob("*.json") if path.stem.isdigit()) if folder.is_dir() else []


def claim_status(triage_dir: Path, mode: str, key: str) -> dict | None:
    """The latest claim on one entry's result in one mode and what its request recorded, or None. Reads only."""
    numbers = _claims(triage_dir, mode, key)
    if not numbers:
        return None
    try:
        claim = json.loads((triage_dir / "claims" / mode / key / f"{numbers[-1]}.json").read_text(encoding="utf-8"))
        attempt = read_attempt(load_record(triage_dir, claim["triage_id"]), mode, claim["attempt"])
    except (OSError, ValueError, KeyError, TypeError, TriageRefused) as exc:
        return {"claims": numbers[-1], "triage_id": None, "state": "invalid",
                "detail": f"The latest claim on this entry cannot be verified ({type(exc).__name__})."}
    if usable(attempt):  # Accepted on receipt, or on an explicit local re-check under the current policy.
        state = "accepted"
    elif attempt["state"] == "none":
        state = "claimed_not_reserved"
    elif attempt["state"] == "complete":  # A paid request with no reply may still have been processed and billed.
        state = "uncertain" if mode == "paid" and attempt["outcome"] == "no_reply" else "failed"
    else:
        state = "uncertain" if attempt.get("sent") else attempt["state"]
    return {"claims": numbers[-1], "triage_id": claim["triage_id"], "claimed_at": claim.get("claimed_at"),
            "state": state, "outcome": attempt.get("outcome"),
            "detail": attempt.get("message") or attempt.get("detail") or attempt.get("outcome_note")}


def pair_key(first: str, second: str, settings_key: str) -> str:
    """Where one comparison is claimed: both entries' input fingerprints in canonical order, so neither order nor other
    entries change it, and the configuration. A relation's own wording and member order stay in its response."""
    low, high = sorted((first, second))
    return f"pairs/{sha256(f'{low}:{high}'.encode('utf-8'))[:32]}-{settings_key}"


def _claim_work(record: dict, mode: str, name: str, work: list[tuple[str, str, set[str]]], reprocess: set[str],
                triage_dir: Path, clock: Callable[[], datetime]) -> list[Path]:
    """Claim every piece of a request's work, each (claim key, what it is, its entry IDs), before anything is
    reserved: its entries to triage and its comparisons. All or none: a refusal removes this call's own claims, which
    nothing has used yet."""
    created: list[Path] = []
    try:
        for key, label, members in work:
            status = claim_status(triage_dir, mode, key)
            if status and status["state"] == "accepted":
                raise TriageRefused(409, f"{label} already has a saved {mode} result, so it is never requested again; "
                                         "nothing was reserved or sent. Preview the selection again")
            if status and not members & reprocess:
                raise TriageRefused(409, f"An earlier {mode} request already claimed {label} (state: "
                                         f"{status['state']}). Requesting it again needs an explicit decision; nothing "
                                         "was reserved or sent")
            folder = triage_dir / "claims" / mode / key
            folder.mkdir(parents=True, exist_ok=True)
            path = folder / f"{(status or {}).get('claims', 0) + 1}.json"
            try:
                keep_record(path, _json_bytes({"triage_id": record["triage_id"], "mode": mode, "attempt": name,
                                               "item_ids": sorted(members), "claimed_at": utc(clock()).isoformat()}))
            except FileExistsError:
                raise TriageRefused(409, f"Another request claimed {label} at the same moment; nothing was reserved "
                                         "or sent") from None
            created.append(path)
    except BaseException:
        for path in created:
            path.unlink(missing_ok=True)
        raise
    return created


