"""Wording of the Treasury findings pilot (insight-text-0.1): fixed templates filled only with stored measurements.

Every number comes from the stored result; nothing is generated by a model. A finding separates what was observed
(dates, source values, changes, ranks), what the comparison adds, a qualified inference, alternatives, and what would
strengthen or weaken it. Limitations that apply to every finding are stated once on the page, not repeated here.
"""
from decimal import Decimal

from . import insight_rules

TEXT_VERSION = "insight-text-0.1"
WINDOW_LABELS = {"W1": "session before the event date to the first session after it",
                 "W5": "session before the event date to the fifth session after it",
                 "PRE": "sixth session before the event date to the session before it"}
SAME_NEWS = "Other news or data on the same sessions: daily data cannot separate them."


def _bp(text: str | None) -> str:
    if text is None:
        return "unavailable"
    value = Decimal(text)
    return f"{'+' if value > 0 else ''}{text} bp"


def _rank(entry: dict) -> str:
    reference = entry.get("reference") or {}
    if "rank" not in reference:
        return "no rank"
    return f"rank {Decimal(reference['rank']):.2f}"


def _measure_row(key: str, entry: dict) -> dict:
    measure, window = key.split(":")
    reference = entry.get("reference") or {}
    return {"key": key, "measure": measure, "label": insight_rules.MEASURES[measure][0], "window": window,
            "window_label": WINDOW_LABELS[window], "span": entry["span"], "start": entry["start"], "end": entry["end"],
            "change_bp": entry["change_bp"], "rank": reference.get("rank"), "smaller": reference.get("smaller"),
            "equal": reference.get("equal"), "eligible": reference.get("eligible"),
            "candidates": reference.get("candidates"), "reference_first_end": reference.get("first_end"),
            "reference_last_end": reference.get("last_end"), "problem": entry.get("problem")}


def _finding(check: dict, table: dict, frequency: dict | None) -> dict:
    rule, subject, window = check["rule"], check["subject"], check["window"]
    get = lambda key: table[key]  # noqa: E731
    if rule == "R1":
        nominal, real, breakeven = get(f"n{subject}:{window}"), get(f"r{subject}:{window}"), get(f"be{subject}:{window}")
        title = f"{subject}-year: an ordinary nominal change with large, offsetting real-yield and breakeven changes"
        adds = (f"The {subject}-year nominal yield changed {_bp(nominal['change_bp'])} ({_rank(nominal)}), which reads "
                f"as ordinary. Its parts moved far more: the inflation-indexed yield {_bp(real['change_bp'])} "
                f"({_rank(real)}) and the breakeven {_bp(breakeven['change_bp'])} ({_rank(breakeven)}), in opposite "
                "directions. Neither the nominal figure nor a 2-year/10-year table shows this.")
        inference = ("Consistent with real yields and inflation compensation moving against each other over these "
                     "sessions while the nominal yield stayed near its starting level. It describes the split; it does "
                     "not attribute it to the release.")
        alternatives = [SAME_NEWS, "Liquidity or seasonal effects in inflation-indexed securities can move the "
                        "breakeven without any change in inflation views.",
                        "Auctions or other supply at this maturity (not in the retained data)."]
        strengthen = ["Intraday nominal and inflation-indexed prices around the release time.",
                      "The same split around comparable releases."]
        weaken = ["A liquidity event or auction in inflation-indexed securities within the window.",
                  "Other inflation-compensation measures, such as inflation swaps, not moving the same way."]
    elif rule == "R2":
        nominal, real, breakeven = get(f"n{subject}:{window}"), get(f"r{subject}:{window}"), get(f"be{subject}:{window}")
        dominant = check["detail"]["dominant"]
        share = Decimal(check["detail"]["share"])
        larger = real if dominant == "inflation-indexed" else breakeven
        total = abs(Decimal(real["change_bp"])) + abs(Decimal(breakeven["change_bp"]))
        part = "real-yield (inflation-indexed)" if dominant == "inflation-indexed" else "breakeven"
        title = f"{subject}-year: a large nominal change came mainly from the {part} component"
        adds = (f"The {subject}-year nominal yield changed {_bp(nominal['change_bp'])} ({_rank(nominal)}). Of its two "
                f"parts, the inflation-indexed yield changed {_bp(real['change_bp'])} and the breakeven "
                f"{_bp(breakeven['change_bp'])}: the {part} change is {abs(Decimal(larger['change_bp']))} of the "
                f"{total} bp the two moved in absolute terms (a share of {share:.2f}). The nominal figure alone does "
                "not say which part moved.")
        inference = (f"Consistent with the move being mainly in {'real yields' if dominant == 'inflation-indexed' else 'inflation compensation'} "
                     f"rather than in {'inflation compensation' if dominant == 'inflation-indexed' else 'real yields'} "
                     "over these sessions, without attributing it to the release.")
        alternatives = [SAME_NEWS, "A breakeven reflects inflation-risk and liquidity premiums as well as expected "
                        "inflation.", "Auctions or other supply at this maturity (not in the retained data)."]
        strengthen = ["Intraday nominal and inflation-indexed prices around the release time.",
                      "The same split around comparable releases."]
        weaken = ["A liquidity event or auction in inflation-indexed securities within the window.",
                  "Other inflation-compensation measures, such as inflation swaps, not moving the same way."]
    elif rule == "R3":
        slope, two, ten = get(f"s2s10:{window}"), get(f"n2:{window}"), get(f"n10:{window}")
        change = Decimal(slope["change_bp"])
        shape = "steepened" if change > 0 else "flattened" if change < 0 else "kept its slope"
        title = f"The 2s10s slope {shape} by an unusual amount"
        adds = (f"The 2-year yield changed {_bp(two['change_bp'])} and the 10-year {_bp(ten['change_bp'])}, so the "
                f"10-year minus 2-year slope changed {_bp(slope['change_bp'])} ({_rank(slope)}): the curve {shape}, "
                "which a single-maturity reading misses.")
        inference = ("Consistent with short and long maturities responding by different amounts over these sessions; "
                     "it does not show why.")
        alternatives = [SAME_NEWS, "Supply or demand concentrated at one end of the curve (not in the retained data)."]
        strengthen = ["Intraday curve data around the release time.", "The same slope change around comparable "
                      "releases."]
        weaken = ["A known supply, index or month-end event at either maturity within the window."]
    else:
        before, after = get(f"{subject}:PRE"), get(f"{subject}:W5")
        label = insight_rules.MEASURES[subject][0]
        first = check["detail"]["direction"] == "before"
        title = (f"{label[0].upper()}{label[1:]}: a large move before the event date, an ordinary one after"
                 if first else f"{label[0].upper()}{label[1:]}: an ordinary move before the event date, a large one "
                               "from it on")
        adds = (f"In the five sessions before the event date the {label} changed {_bp(before['change_bp'])} "
                f"({_rank(before)}); from the session before it to the fifth session after, "
                f"{_bp(after['change_bp'])} ({_rank(after)}). The timing, not just the size, is what this adds.")
        inference = ("Consistent with repricing that happened before the event date (expectations formed earlier, or "
                     "other news); the data cannot tell which." if first else
                     "Consistent with movement concentrated from the event date on; daily data cannot show whether it "
                     "followed the release itself.")
        alternatives = ([SAME_NEWS, "Anticipation through speeches, previews or other releases before the event date."]
                        if first else [SAME_NEWS, "Later news within the five sessions after the event date."])
        strengthen = ["Intraday data around the release time.", "Dated news and other releases across the window."]
        weaken = ["A dated, unrelated event explaining the move in the same sessions."]
    observed = check["measures"]
    return {"check": insight_rules.check_key(check), "rule": rule, "rule_text": insight_rules.RULES[rule],
            "title": title, "window": window, "window_label": WINDOW_LABELS.get(window) if window else None,
            "observations": observed, "adds": adds, "inference": inference, "alternatives": alternatives,
            "strengthen": strengthen, "weaken": weaken, "frequency": frequency}


def render(result: dict, comparison: dict | None, nearby: list[dict]) -> dict:
    """The page's view of one stored result: measurements, findings, checks not met, and context."""
    evaluation = result["evaluation"]
    table = evaluation["table"]
    counts = (comparison or {}).get("counts", {}).get("checks", {})
    size = (comparison or {}).get("counts", {}).get("size")
    findings, other = [], []
    for check in evaluation["checks"]:
        key = insight_rules.check_key(check)
        frequency = {**counts[key], "sessions": size} if key in counts else None
        if check["outcome"] == "met":
            findings.append(_finding(check, table, frequency))
        else:
            other.append({"check": key, "rule": check["rule"], "subject": check["subject"], "window": check["window"],
                          "outcome": check["outcome"], "detail": check["detail"] if isinstance(check["detail"], str)
                          else None, "frequency": frequency})
    evaluable = sum(1 for check in evaluation["checks"] if check["outcome"] != "not_evaluable")
    summary = (f"{len(findings)} of {evaluable} evaluable rule checks met their conditions." if findings else
               f"Checked: none of the {evaluable} evaluable rule checks met its conditions." if evaluable else
               "No rule check could be evaluated.")
    return {"text_version": TEXT_VERSION, "date": result["context_date"], "summary": summary,
            "event_on_grid": evaluation.get("event_on_grid"),
            "windows": {key: {**value, "label": WINDOW_LABELS[key]} for key, value in evaluation["windows"].items()},
            "measures": [_measure_row(key, entry) for key, entry in table.items()], "findings": findings,
            "other_checks": other, "policy_changes": result["policy_changes"], "nearby": nearby,
            "series": result["series"], "rules": insight_rules.RULES,
            "comparison": {"comparison_id": comparison["comparison_id"], "seed": comparison["seed"],
                           "size": size, "range": comparison["counts"]["range"],
                           "candidates": comparison["counts"]["candidates"],
                           "note": ("Comparison sessions are dated sessions chosen by a recorded seed from a fixed "
                                    "range, skipping any whose windows contain a retained event date. They are not "
                                    "news-free, and how often a pattern appears on them is a description, not a "
                                    "probability.")} if comparison else None}
