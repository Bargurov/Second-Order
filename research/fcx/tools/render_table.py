"""Write research/fcx/data-table.md from facts.json: the key-figure tables, then every record.

The key tables are fixed lists of record ids (KEY_TABLES below), so a figure appears only where its period and basis
belong: quarter, nine-month and annual columns are separate, and consolidated, attributable and noncontrolling rows
are labelled. Run after any change to facts.json, then run check_facts.py.

Run: python -I research/fcx/tools/render_table.py
"""
import json
from pathlib import Path

FOLDER = Path(__file__).resolve().parents[1]
SHORT = {"10k-2025": "10-K 2025", "10q-2026q3": "10-Q Q3 2026", "release-2026q3": "Release Q3 2026",
         "news-2026-11-04": "Release 2026-11-04 (Bagdad)"}
KIND = {"published": "P", "computed": "C", "assumption": "A"}
BASIS = {"consolidated": "consolidated", "attributable_to_common_stock": "attributable to common stock",
         "noncontrolling_interests": "noncontrolling interests",
         "net_of_noncontrolling_interests": "net of noncontrolling interests",
         "company_definition": "company definition"}

# Each table: title, note, columns, rows of [label, [record id or null per column]]. A row holds one basis only.
KEY_TABLES = json.loads((FOLDER / "tools" / "key_tables.json").read_bytes().decode("utf-8"))


def basis_text(basis: str) -> str:
    if basis in BASIS:
        return BASIS[basis]
    return basis.replace(":", ": ", 1)


def cell(record: dict | None, with_unit: bool = False) -> str:
    if record is None:
        return "—"
    shown = record.get("display") or format_value(record)
    return f"{shown} {record['unit']} {KIND[record['kind']]}" if with_unit else f"{shown} {KIND[record['kind']]}"


def format_value(record: dict) -> str:
    value = float(record["value"])
    places = record.get("decimals", 0)
    text = f"{abs(value):,.{places}f}"
    return f"({text})" if value < 0 else text


def where(record: dict) -> str:
    if record["kind"] == "published":
        page = record.get("printed_page") or record["page"]
        return f"{SHORT[record['source']]}, p. {page}"
    if record["kind"] == "computed":
        return "computed: " + record["formula"]
    return "assumption"


def escape(text: str) -> str:
    return str(text).replace("|", "\\|").replace("\n", " ")


def main() -> None:
    data = json.loads((FOLDER / "facts.json").read_bytes().decode("utf-8"))
    records = data["records"]
    by_id = {r["id"]: r for r in records}
    out = ["# FCX stage 1: data table", "",
           "Generated by `tools/render_table.py` from `facts.json`; do not edit by hand. Kinds: **P** published (quoted "
           "from a retained report, page given), **C** computed by this project (formula given), **A** an assumption. "
           "Pages are the printed page numbers (release supplemental schedules use roman numerals); the Where column lists "
           "sources in column order. Units are those "
           "the company prints. \"—\" means the report gives no figure for that cell.", ""]
    for table in KEY_TABLES:
        out += [f"## {table['title']}", "", table["note"], ""]
        out.append("| Metric | Basis | Unit | " + " | ".join(table["columns"]) + " | Where |")
        out.append("| --- | --- | --- | " + " | ".join("---:" for _ in table["columns"]) + " | --- |")
        for label, ids in table["rows"]:
            present = [by_id[i] for i in ids if i]
            missing = [i for i in ids if i and i not in by_id]
            if missing:
                raise SystemExit(f"key table row {label!r} names unknown ids {missing}")
            first = present[0]
            bases = {r["basis"] for r in present}
            if len(bases) > 1:
                raise SystemExit(f"key table row {label!r} mixes bases {sorted(bases)}")
            units = {r["unit"] for r in present}
            mixed = len(units) > 1
            places = list(dict.fromkeys(where(r) for r in present))  # in column order
            out.append(f"| {escape(label)} | {basis_text(first['basis'])} | {'in each cell' if mixed else first['unit']} | "
                       + " | ".join(cell(by_id.get(i), mixed) if i else "—" for i in ids)
                       + f" | {escape('; '.join(places))} |")
        out.append("")
    out += ["## Every record", "",
            "Published records quote the report; `tools/check_facts.py` finds each quote on its page in the retained "
            "file. Computed records give their formula over record ids.", ""]
    out.append("| Id | Metric | Period | Value | Unit | Basis | Kind | Where | Location |")
    out.append("| --- | --- | --- | ---: | --- | --- | --- | --- | --- |")
    for record in records:
        if record["kind"] == "assumption":
            continue
        out.append(f"| `{record['id']}` | {escape(record['metric'])} | {record['period']['label']} | "
                   f"{record.get('display') or format_value(record)} | {record['unit']} | {basis_text(record['basis'])} "
                   f"| {KIND[record['kind']]} | {escape(where(record))} | {escape(record.get('location', ''))} |")
    out += ["", "## Assumptions", ""]
    for record in records:
        if record["kind"] == "assumption":
            out.append(f"- `{record['id']}`: {record['statement']} Used by: "
                       + ", ".join(f"`{u}`" for u in record["used_by"]) + ".")
    (FOLDER / "data-table.md").write_bytes(("\n".join(out) + "\n").encode("utf-8"))
    print(f"data-table.md: {len(KEY_TABLES)} key tables, {len(records)} records")


if __name__ == "__main__":
    main()
